-- MySQL 8 equivalent of ha_schema.sql.
CREATE TABLE IF NOT EXISTS tasks (
  id VARCHAR(64) PRIMARY KEY, uid VARCHAR(128) NOT NULL, mode VARCHAR(32) NOT NULL,
  status VARCHAR(32) NOT NULL, payload JSON NOT NULL, version BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS task_items (
  task_id VARCHAR(64) NOT NULL, item_index INT NOT NULL, status VARCHAR(32) NOT NULL,
  payload JSON NOT NULL, version BIGINT NOT NULL DEFAULT 0,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (task_id, item_index), CONSTRAINT task_items_task_fk FOREIGN KEY (task_id) REFERENCES tasks(id) ON DELETE CASCADE,
  INDEX task_items_status_idx (status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS quota_cards (
  code VARCHAR(128) PRIMARY KEY, quota BIGINT NOT NULL, used_quota BIGINT NOT NULL DEFAULT 0,
  reserved_quota BIGINT NOT NULL DEFAULT 0, status VARCHAR(32) NOT NULL, version BIGINT NOT NULL DEFAULT 0,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS quota_ledger (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, request_id VARCHAR(128) NOT NULL, card_code VARCHAR(128) NOT NULL,
  task_id VARCHAR(64), item_index INT, delta BIGINT NOT NULL, kind VARCHAR(32) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), UNIQUE KEY quota_ledger_request_kind (request_id, kind),
  CONSTRAINT quota_ledger_card_fk FOREIGN KEY (card_code) REFERENCES quota_cards(code)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS execution_leases (
  lease_key VARCHAR(256) PRIMARY KEY, coordinator_id VARCHAR(256) NOT NULL, task_id VARCHAR(64) NOT NULL,
  item_index INT NOT NULL, kind VARCHAR(32) NOT NULL, expires_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6), INDEX execution_leases_expiry_idx (expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS coordinator_members (
  coordinator_id VARCHAR(256) PRIMARY KEY, last_seen_at DATETIME(6) NOT NULL,
  is_leader BOOLEAN NOT NULL DEFAULT FALSE, metadata JSON NOT NULL
) ENGINE=InnoDB;
